"""Build slides 1 and 3–20 using the approved slide-2 recording treatment."""

from concurrent.futures import ThreadPoolExecutor
import hashlib
import os
from pathlib import Path
import re
import subprocess


OUTPUT = Path(__file__).resolve().parents[1]
BACKGROUNDS = OUTPUT / "composition/assets/backgrounds"
TREATMENTS = OUTPUT / "treatments"
CLI = Path.home() / "Library/Application Support/HyperFrames/agent-cli/bin/hyperframes"
FFMPEG = Path.home() / "Library/Application Support/HyperFrames/runtimes/ffmpeg-darwin-arm64-4d7f2b1c517e/ffmpeg"
ENV = {**os.environ, "PATH": f"{FFMPEG.parent}:{os.environ['PATH']}"}
TEMPLATE = (TREATMENTS / "slide-02/index.html").read_text()
MARKER = "<!-- Generated by treatments/build-recording.py from the approved slide-2 treatment. -->"


def metadata(path):
    rows = subprocess.check_output(
        ["magick", "identify", "-format", "%w %h %T\n", str(path)], text=True
    ).splitlines()
    frames = [list(map(int, row.split())) for row in rows]
    return frames[0][0], frames[0][1], [frame[2] for frame in frames]


def build(number):
    name = f"{number:02}"
    source = BACKGROUNDS / f"{name}.gif"
    width, height, delays = metadata(source)
    duration_cs = sum(delays)
    assert duration_cs % 10 == 0, f"{source}: loop must fit 100 ms output frames"
    count = duration_cs // 10
    duration = f"{duration_cs / 100:g}"
    padded_width, padded_height = width + width % 2, height + height % 2
    project = TREATMENTS / f"slide-{name}"
    project.mkdir(exist_ok=True)
    html_path = project / "index.html"
    if html_path.exists() and MARKER not in html_path.read_text():
        raise RuntimeError(f"Refusing to overwrite independently authored {html_path}")
    html = TEMPLATE.replace("Slide 2", f"Slide {number}")
    html = html.replace("720px", f"{padded_width}px").replace("356px", f"{padded_height}px")
    html = html.replace('data-width="720"', f'data-width="{padded_width}"')
    html = html.replace('data-height="356"', f'data-height="{padded_height}"')
    html = html.replace('data-duration="5.4"', f'data-duration="{duration}"')
    html_path.write_text(html.replace("<head>", f"<head>\n  {MARKER}", 1))
    (project / "assets").mkdir(exist_ok=True)
    frames = project / ".hyperframes/recording-frames"
    temporary = BACKGROUNDS / f"{name}-recording.tmp.gif"
    destination = BACKGROUNDS / f"{name}-recording.gif"
    times = ",".join(f"{i / 10:.1f}" for i in range(count))
    commands = [
        [str(FFMPEG), "-y", "-hide_banner", "-loglevel", "error", "-ignore_loop", "1",
         "-i", str(source), "-vf", "pad=ceil(iw/2)*2:ceil(ih/2)*2,fps=10", "-t", duration,
         "-an", "-c:v", "libx264", "-crf", "16", "-pix_fmt", "yuv420p",
         "-movflags", "+faststart", "assets/source.mp4"],
        [str(CLI), "check", ".", "--json"],
        [str(CLI), "snapshot", ".", "--at", times, "--no-end",
         "--output", str(frames), "--json"],
        [str(FFMPEG), "-y", "-hide_banner", "-loglevel", "error", "-framerate", "10",
         "-pattern_type", "glob", "-i", str(frames / "frame-*.png"),
         "-filter_complex", f"[0:v]crop=w={width}:h={height}:x=0:y=0:exact=1,split[a][b];"
         "[a]palettegen=stats_mode=full[p];[b][p]paletteuse=dither=sierra2_4a",
         "-loop", "0", str(temporary)],
    ]
    print(f"Building slide {name}: {width}×{height}, {duration}s; log: {project / 'build.log'}", flush=True)
    with (project / "build.log").open("w") as log:
        for command in commands:
            subprocess.run(command, cwd=project, env=ENV, stdout=log, stderr=subprocess.STDOUT, check=True)
    actual_width, actual_height, actual_delays = metadata(temporary)
    assert (actual_width, actual_height) == (width, height), f"Wrong dimensions: {temporary}"
    assert actual_delays == [10] * count, f"Wrong loop timing: {temporary}"
    verbose = subprocess.check_output(["magick", "identify", "-verbose", f"{temporary}[0]"], text=True)
    assert re.search(r"Iterations: 0\b", verbose), f"Looping disabled: {temporary}"
    first = subprocess.check_output(["magick", f"{temporary}[0]", "rgba:-"])
    second = subprocess.check_output(["magick", f"{temporary}[1]", "rgba:-"])
    assert first != second, f"Frozen noise: {temporary}"
    temporary.replace(destination)
    print(f"PASS slide {name}: {count} frames; {destination.stat().st_size / 2**20:.1f} MiB", flush=True)


if __name__ == "__main__":
    protected = [*BACKGROUNDS.glob("[0-9][0-9].gif"), BACKGROUNDS / "02-recording.gif"]
    before = {path: hashlib.sha256(path.read_bytes()).digest() for path in protected}
    # Two native rendering sessions bound peak resource use while independent clips build in parallel.
    with ThreadPoolExecutor(max_workers=2) as workers:
        list(workers.map(build, [number for number in range(1, 21) if number != 2]))
    assert all(hashlib.sha256(path.read_bytes()).digest() == digest for path, digest in before.items()), "Approved media changed"
    total = sum(path.stat().st_size for path in BACKGROUNDS.glob("??-recording.gif"))
    print(f"PASS: all 20 treated GIFs ready, {total / 2**20:.1f} MiB; approved base GIFs and slide 2 unchanged.", flush=True)
